-- Fundusaufnahmen automatisch von der Funduskamera (iCare DRSplus) übernehmen.
--
-- Ablauf: Die Kamera legt jede Aufnahme selbst als DICOM in einen freigegebenen
-- Ordner auf dem Praxis-PC. Das Hilfsprogramm tools/fundus-import liest daraus
-- Name, Geburtsdatum, Patienten-ID, Auge und Aufnahmezeit und schickt das Bild
-- an die Edge Function fundus-import. Die legt die Datei im privaten Bucket
-- kunde-dokumente ab und trägt sie hier in den Eingang ein.
--
-- Zuordnung:
--   1. Patienten-ID der Kamera = Kundennummer (und Geburtsdatum widerspricht
--      nicht)                                       → automatisch beim Kunden
--   2. sonst Nachname + Vorname + Geburtsdatum passen auf genau einen Kunden
--                                                   → automatisch beim Kunden
--   3. sonst bleibt die Aufnahme "offen" und wird im Fundusarchiv unter
--      „Neue Aufnahmen – noch zuzuordnen“ von Hand zugeordnet.
-- Zugeordnet heißt: ein Eintrag in kunde_dokument (Art „Fundusaufnahme“), die
-- Aufnahme erscheint damit unter Dokumente in der Kundenkartei.
--
-- Neue Tabelle und Funktionen; einzige Änderung an Bestehendem: der Trigger
-- kunde_dokument_schuetzen kennt jetzt einen Absender für Einträge ohne
-- Anmeldung (Import), statt „unbekannt“. Keine Änderung an bestehenden Daten.

-- 1. Eingang ------------------------------------------------------------------

create table if not exists public.fundus_eingang (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  "Pfad" text not null unique check (length(trim("Pfad")) > 0),
  "Dateiname" text not null,
  "Typ" text not null default 'image/jpeg',
  "Groesse" bigint check ("Groesse" is null or "Groesse" >= 0),
  "Hash" text not null unique,
  "Aufnahme" timestamptz,
  "Auge" text check ("Auge" is null or "Auge" in ('R', 'L')),
  "Patient_Nachname" text,
  "Patient_Vorname" text,
  "Patient_Geburtsdatum" date,
  "Patient_ID" text,
  "Geraet" text,
  "Status" text not null default 'offen'
    check ("Status" in ('offen', 'zugeordnet', 'verworfen')),
  kunde_id bigint references public.kunde (id) on delete cascade,
  dokument_id bigint references public.kunde_dokument (id) on delete set null,
  zugeordnet_von text,
  zugeordnet_am timestamptz
);

comment on table public.fundus_eingang is
  'Von der Funduskamera übernommene Aufnahmen. Datei im Bucket kunde-dokumente unter "Pfad"; zugeordnet = Eintrag in kunde_dokument.';
comment on column public.fundus_eingang."Hash" is
  'SHA-256 der Bilddatei; verhindert, dass dieselbe Aufnahme doppelt übernommen wird.';
comment on column public.fundus_eingang."Patient_ID" is
  'Patienten-ID, wie sie an der Kamera eingegeben wurde (am besten die Kundennummer).';
comment on column public.fundus_eingang.zugeordnet_von is
  'E-Mail des Benutzers oder „DRSplus-Import (automatisch)“.';

create index if not exists fundus_eingang_offen_idx
  on public.fundus_eingang (created_at desc) where "Status" = 'offen';
create index if not exists fundus_eingang_kunde_idx
  on public.fundus_eingang (kunde_id);
create index if not exists fundus_eingang_dokument_idx
  on public.fundus_eingang (dokument_id);

-- Lesen dürfen alle aktiven Rollen; schreiben nur die Edge Function (Service-
-- Rolle) und die Funktionen unten.
alter table public.fundus_eingang enable row level security;

drop policy if exists rolle_lesen on public.fundus_eingang;
create policy rolle_lesen on public.fundus_eingang
  for select to authenticated using (public.darf_lesen());

revoke insert, update, delete, truncate on public.fundus_eingang from anon, authenticated;

-- 2. "hochgeladen von" für Einträge ohne Anmeldung ----------------------------

create or replace function public.kunde_dokument_schuetzen()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    new.hochgeladen_von := coalesce(
      nullif(auth.jwt() ->> 'email', ''),
      nullif(current_setting('app.hochgeladen_von', true), ''),
      'unbekannt'
    );
  else
    new.kunde_id := old.kunde_id;
    new."Pfad" := old."Pfad";
    new.hochgeladen_von := old.hochgeladen_von;
    new.created_at := old.created_at;
  end if;
  return new;
end;
$$;

-- 3. Hilfsfunktionen ------------------------------------------------------------

-- Namen vergleichbar machen: klein, Umlaute ausgeschrieben, nur Buchstaben.
-- „Hölzl“, „HOELZL“ und „Hoelzl“ werden gleich.
create or replace function public.fundus_namen_normal(wert text)
returns text
language sql
immutable
set search_path = public
as $$
  select regexp_replace(
    replace(replace(replace(replace(
      lower(coalesce(wert, '')),
      'ä', 'ae'), 'ö', 'oe'), 'ü', 'ue'), 'ß', 'ss'),
    '[^a-z]', '', 'g'
  );
$$;

-- Kunde zu den Daten der Kamera, nur wenn er eindeutig ist (sonst null).
create or replace function public.fundus_kunde_finden(
  p_patient_id text,
  p_nachname text,
  p_vorname text,
  p_geburtsdatum date
)
returns bigint
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  treffer bigint[];
begin
  -- 1. Patienten-ID = Kundennummer; ein abweichendes Geburtsdatum verhindert
  --    die automatische Zuordnung (Tippfehler bei der ID).
  if nullif(btrim(coalesce(p_patient_id, '')), '') is not null then
    select array_agg(k.id) into treffer
    from public.kunde k
    where btrim(k."KundenNummer") = btrim(p_patient_id)
      and (
        p_geburtsdatum is null
        or k."Geburtsdatum" is null
        or k."Geburtsdatum"::date = p_geburtsdatum
      );
    if coalesce(array_length(treffer, 1), 0) = 1 then
      return treffer[1];
    end if;
  end if;

  -- 2. Nachname + Vorname + Geburtsdatum
  if p_geburtsdatum is not null
     and public.fundus_namen_normal(p_nachname) <> ''
     and public.fundus_namen_normal(p_vorname) <> '' then
    select array_agg(k.id) into treffer
    from public.kunde k
    where k."Geburtsdatum"::date = p_geburtsdatum
      and public.fundus_namen_normal(k."Nachname") = public.fundus_namen_normal(p_nachname)
      and public.fundus_namen_normal(k."Vorname") = public.fundus_namen_normal(p_vorname);
    if coalesce(array_length(treffer, 1), 0) = 1 then
      return treffer[1];
    end if;
  end if;

  return null;
end;
$$;

-- Aufnahme beim Kunden ablegen (intern, ohne Rechteprüfung).
create or replace function public.fundus_eingang_ablegen(
  p_eingang bigint,
  p_kunde bigint,
  p_wer text
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  e public.fundus_eingang;
  dok_id bigint;
  name text;
begin
  select * into e from public.fundus_eingang where id = p_eingang for update;
  if not found then
    raise exception 'Aufnahme % nicht gefunden.', p_eingang;
  end if;
  if e."Status" <> 'offen' then
    raise exception 'Die Aufnahme ist schon zugeordnet oder verworfen.';
  end if;
  if not exists (select 1 from public.kunde where id = p_kunde) then
    raise exception 'Kunde % nicht gefunden.', p_kunde;
  end if;

  name := 'Fundus'
    || case e."Auge" when 'R' then ' rechts' when 'L' then ' links' else '' end
    || coalesce(' ' || to_char(e."Aufnahme" at time zone 'Europe/Berlin', 'DD.MM.YYYY HH24:MI'), '');

  perform set_config('app.hochgeladen_von', p_wer, true);
  insert into public.kunde_dokument (kunde_id, "Name", "Art", "Datum", "Pfad", "Typ", "Groesse")
  values (
    p_kunde,
    name,
    'Fundusaufnahme',
    coalesce((e."Aufnahme" at time zone 'Europe/Berlin')::date, (e.created_at at time zone 'Europe/Berlin')::date),
    e."Pfad",
    e."Typ",
    e."Groesse"
  )
  returning id into dok_id;
  perform set_config('app.hochgeladen_von', '', true);

  update public.fundus_eingang
  set "Status" = 'zugeordnet',
      kunde_id = p_kunde,
      dokument_id = dok_id,
      zugeordnet_von = p_wer,
      zugeordnet_am = now()
  where id = p_eingang;

  return dok_id;
end;
$$;

revoke all on function public.fundus_eingang_ablegen(bigint, bigint, text) from public, anon, authenticated;
revoke all on function public.fundus_kunde_finden(text, text, text, date) from public, anon, authenticated;

-- 4. Automatisch zuordnen, sobald eine Aufnahme ankommt -------------------------

create or replace function public.fundus_eingang_automatisch()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  kid bigint;
begin
  kid := public.fundus_kunde_finden(
    new."Patient_ID", new."Patient_Nachname", new."Patient_Vorname", new."Patient_Geburtsdatum"
  );
  if kid is not null then
    perform public.fundus_eingang_ablegen(new.id, kid, 'DRSplus-Import (automatisch)');
  end if;
  return null;
end;
$$;

revoke all on function public.fundus_eingang_automatisch() from public, anon, authenticated;

drop trigger if exists fundus_eingang_automatisch on public.fundus_eingang;
create trigger fundus_eingang_automatisch
  after insert on public.fundus_eingang
  for each row execute function public.fundus_eingang_automatisch();

-- 5. Von Hand zuordnen / verwerfen / Vorschläge (aus der App) ------------------

create or replace function public.fundus_zuordnen(p_eingang bigint, p_kunde bigint)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.darf_bearbeiten() then
    raise exception 'Keine Berechtigung, Fundusaufnahmen zuzuordnen.';
  end if;
  return public.fundus_eingang_ablegen(
    p_eingang, p_kunde, coalesce(nullif(auth.jwt() ->> 'email', ''), 'unbekannt')
  );
end;
$$;

create or replace function public.fundus_verwerfen(p_eingang bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.darf_bearbeiten() then
    raise exception 'Keine Berechtigung, Fundusaufnahmen zu verwerfen.';
  end if;
  update public.fundus_eingang
  set "Status" = 'verworfen',
      zugeordnet_von = coalesce(nullif(auth.jwt() ->> 'email', ''), 'unbekannt'),
      zugeordnet_am = now()
  where id = p_eingang and "Status" = 'offen';
  if not found then
    raise exception 'Die Aufnahme ist schon zugeordnet oder verworfen.';
  end if;
end;
$$;

-- Bis zu 5 Kunden, die zur Aufnahme passen könnten (gleiches Geburtsdatum
-- und/oder ähnlicher Name), bestes zuerst.
create or replace function public.fundus_vorschlaege(p_eingang bigint)
returns table (
  kunde_id bigint,
  "Nachname" text,
  "Vorname" text,
  "Geburtsdatum" date,
  "KundenNummer" text,
  punkte numeric
)
language plpgsql
stable
security definer
set search_path = public, extensions
as $$
declare
  e public.fundus_eingang;
  nn text;
  vn text;
begin
  if not public.darf_lesen() then
    raise exception 'Keine Berechtigung.';
  end if;
  select * into e from public.fundus_eingang where id = p_eingang;
  if not found then
    return;
  end if;
  nn := public.fundus_namen_normal(e."Patient_Nachname");
  vn := public.fundus_namen_normal(e."Patient_Vorname");

  return query
  with kandidaten as (
    select
      k.id,
      k."Nachname"::text as nachname,
      k."Vorname"::text as vorname,
      k."Geburtsdatum"::date as geb,
      k."KundenNummer"::text as nr,
      (case when e."Patient_Geburtsdatum" is not null
                 and k."Geburtsdatum"::date = e."Patient_Geburtsdatum" then 2 else 0 end)
      + (case when nullif(btrim(coalesce(e."Patient_ID", '')), '') is not null
                 and btrim(k."KundenNummer") = btrim(e."Patient_ID") then 2 else 0 end)
      + (case when nn <> '' then similarity(public.fundus_namen_normal(k."Nachname"), nn) else 0 end)
      + (case when vn <> '' then similarity(public.fundus_namen_normal(k."Vorname"), vn) * 0.5 else 0 end)
        as p
    from public.kunde k
    where (e."Patient_Geburtsdatum" is not null and k."Geburtsdatum"::date = e."Patient_Geburtsdatum")
       or (nullif(btrim(coalesce(e."Patient_ID", '')), '') is not null and btrim(k."KundenNummer") = btrim(e."Patient_ID"))
       or (e."Patient_Nachname" is not null and length(e."Patient_Nachname") >= 2
           and k."Nachname" ilike '%' || left(e."Patient_Nachname", 3) || '%')
  )
  select c.id, c.nachname, c.vorname, c.geb, c.nr, round(c.p::numeric, 2)
  from kandidaten c
  where c.p >= 0.5
  order by c.p desc, c.nachname, c.vorname
  limit 5;
end;
$$;

revoke all on function public.fundus_zuordnen(bigint, bigint) from public, anon;
revoke all on function public.fundus_verwerfen(bigint) from public, anon;
revoke all on function public.fundus_vorschlaege(bigint) from public, anon;
grant execute on function public.fundus_zuordnen(bigint, bigint) to authenticated;
grant execute on function public.fundus_verwerfen(bigint) to authenticated;
grant execute on function public.fundus_vorschlaege(bigint) to authenticated;
grant execute on function public.fundus_namen_normal(text) to authenticated;

