-- Terminanfragen aus dem KI-Telefonassistenten (Edge Function
-- telefon-termin). Anfragen landen bewusst NICHT direkt in "termin": Die
-- KI kennt den Kalender nicht, und ein neuer Anrufer hat noch keinen Kunden
-- (kunde.Anrede ist Pflicht). Das Team prüft die Anfrage und legt den Termin
-- an. Nur Schema, keine Daten.

create table if not exists public.telefon_terminanfrage (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  kunde_id bigint references public.kunde (id),
  "Name" text,
  "Telefon" text,
  "Wunschtermin" timestamptz,
  "Anliegen" text,
  "Status" text not null default 'neu'
    check ("Status" in ('neu', 'termin_angelegt', 'abgelehnt'))
);

comment on table public.telefon_terminanfrage is
  'Terminwünsche aus dem KI-Telefonassistenten, kunde_id nur gesetzt, wenn die Rufnummer genau einem Kunden gehört';

create index if not exists telefon_terminanfrage_status_idx
  on public.telefon_terminanfrage ("Status");

alter table public.telefon_terminanfrage enable row level security;

drop policy if exists "Authenticated users can manage telefon_terminanfrage"
  on public.telefon_terminanfrage;
create policy "Authenticated users can manage telefon_terminanfrage"
  on public.telefon_terminanfrage
  for all
  to authenticated
  using (true)
  with check (true);

-- Kunde zur Rufnummer: vergleicht die letzten 9 Ziffern (ohne +49/0 und
-- Leerzeichen) und liefert die id nur bei genau einem Treffer.
create or replace function public.finde_kunde_nach_telefon(p_telefon text)
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  with eingabe as (
    select right(regexp_replace(coalesce(p_telefon, ''), '\D', '', 'g'), 9) as ziffern
  ), treffer as (
    select k.id
    from public.kunde k, eingabe e
    where length(e.ziffern) = 9
      and (
        right(regexp_replace(coalesce(k."TelefonnummerPrivat", ''), '\D', '', 'g'), 9) = e.ziffern
        or right(regexp_replace(coalesce(k."TelefonnummerGeschaeftlich", ''), '\D', '', 'g'), 9) = e.ziffern
      )
  )
  select case when count(*) = 1 then min(id) end from treffer;
$$;

revoke all on function public.finde_kunde_nach_telefon(text) from public, anon, authenticated;
grant execute on function public.finde_kunde_nach_telefon(text) to service_role;
